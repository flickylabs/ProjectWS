/**
 * Improve Korean dialogue quality for spouse-01 interrogation channel.
 * Only modifies `text` and `behaviorHint` fields in variants.
 * Preserves all structural fields, tags, sourceRefs, keys.
 */
const fs = require('fs');
const path = require('path');

const FILE = path.join(__dirname, '..', 'src', 'data', 'scriptedText', 'spouse-01.json');
const data = JSON.parse(fs.readFileSync(FILE, 'utf8'));
const entries = data.channels.interrogation.entries;

let modCount = 0;

function patch(key, variantIdx, text, behaviorHint) {
  const entry = entries.find(e => e.key === key);
  if (!entry) { console.error('Missing key:', key); return; }
  const v = entry.variants[variantIdx];
  if (!v) { console.error('Missing variant:', key, variantIdx); return; }
  if (text) { v.text = text; modCount++; }
  if (behaviorHint) { v.behaviorHint = behaviorHint; }
}

