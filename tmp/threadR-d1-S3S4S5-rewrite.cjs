function applyRewrites(filePath) {
  const raw = fs.readFileSync(filePath, 'utf8');
  const data = JSON.parse(raw);

  let changed = 0;
  let skipped = 0;

  const entries = data.channels.interrogation.entries;
  for (const entry of entries) {
    if (entry.disputeId !== 'd-1') continue;
    if (!['S3', 'S4', 'S5'].includes(entry.lieState)) continue;

    for (const v of entry.variants) {
      if (REWRITES[v.id]) {
        const oldText = v.text;
        v.text = REWRITES[v.id];
        if (oldText !== v.text) {
          changed++;
        } else {
          skipped++;
        }
      }
    }
  }

  // 검증
  const appliedIds = new Set();
  for (const entry of entries) {
    for (const v of entry.variants) {
      if (REWRITES[v.id]) appliedIds.add(v.id);
    }
  }
  const missing = Object.keys(REWRITES).filter(id => !appliedIds.has(id));
  if (missing.length > 0) {
    console.error('WARNING: 미적용 ID:', missing);
  }

  fs.writeFileSync(filePath, JSON.stringify(data, null, 2), 'utf8');
  console.log(`완료: ${changed}개 변경, ${skipped}개 동일(스킵), ${missing.length}개 미발견`);
  return { changed, skipped, missing };
}

