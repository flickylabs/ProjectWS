function applyTexts(entries, replacements) {
  for (const [key, texts] of Object.entries(replacements)) {
    const entry = entries.find((candidate) => candidate.key === key)
    if (!entry) {
      throw new Error(`Missing entry: ${key}`)
    }
    if (entry.variants.length !== texts.length) {
      throw new Error(`Variant count mismatch for ${key}`)
    }
    entry.variants.forEach((variant, index) => {
      variant.text = texts[index]
    })
  }
}

