for (const entry of data.channels.interrogation.entries) {
  if (entry.party !== 'b' || entry.lieState !== 'S5') continue;
  const group = extras[entry.disputeId]?.[entry.questionType];
  if (!group) continue;

  for (let i = 0; i < Math.min(4, entry.variants.length); i += 1) {
    const variant = entry.variants[i];
    const sentences = splitSentences(variant.text);
    if (sentences.length < 3) {
      sentences.push(group[i]);
      variant.text = sentences.join(' ');
    }
  }
}

