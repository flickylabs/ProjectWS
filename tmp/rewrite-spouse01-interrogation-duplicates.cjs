let updated = 0;
for (const entry of bundle.channels.interrogation.entries) {
  const v1 = entry.variants.find((variant) => variant.id.endsWith('#1'));
  const v4 = entry.variants.find((variant) => variant.id.endsWith('#4'));
  if (!v1 || !v4 || v1.text !== v4.text) continue;
  const next = paraphrases.get(v4.text);
  if (!next) {
    console.warn(`missing paraphrase for ${entry.key}`);
    continue;
  }
  v4.text = next;
  updated += 1;
}

fs.writeFileSync(filePath, JSON.stringify(bundle, null, 2) + '\n', 'utf8');
console.log(`updated ${updated} interrogation variants`);
