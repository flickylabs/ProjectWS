const CASE_QUESTIONS: Record<string, EvidenceQuestionSpec> = {
  'friend-01': FRIEND_01_EVIDENCE_QUESTIONS,
}

function clampStage(stage: number | undefined): number {
  if (!stage || Number.isNaN(stage)) return 1
  return Math.min(3, Math.max(1, Math.trunc(stage)))
}

export function getStageAwareEvidencePresent(
  input: EvidencePresentationScriptInput,
): EvidencePresentationScript | null {
  if (getRuntimeScriptLocale() !== 'ko') return null

  const spec = CASE_SCRIPTS[input.caseId]?.[input.evidenceId]
  if (!spec) return null

  const stage = clampStage(input.investigationStage)
  const fact = spec.partyFacts?.[input.party]?.[stage] ?? spec.facts[stage] ?? spec.facts[1]
  const stance = spec.stances[input.party]?.[input.lieBand]
  if (!fact || !stance) return null

  return {
    text: `${fact} ${stance}`,
    behaviorHint: BEHAVIOR_HINT_BY_BAND[input.lieBand],
  }
}

export function getStageAwareEvidenceQuestion(
  input: Omit<EvidencePresentationScriptInput, 'lieBand'>,
): string | null {
  if (getRuntimeScriptLocale() !== 'ko') return null

  const stage = clampStage(input.investigationStage)
  return CASE_QUESTIONS[input.caseId]?.[input.evidenceId]?.[input.party]?.[stage] ?? null
}
